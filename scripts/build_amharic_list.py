#!/usr/bin/env python3
"""Build the bundled Amharic stopword list from your corpora (v0.2.1).

    python scripts/build_amharic_list.py --cc100 am.txt --gpac GPAC.txt --top 300 --work-dir build_out
    python scripts/build_amharic_list.py --cc100 am.txt --gpac GPAC.txt --reuse-state --work-dir build_out   # no recount

Each corpus is counted separately (tf + idf + entropy, as in the 2018 paper), then:
  * combined.txt   scored on the two corpora merged
  * consensus.txt  scored per corpus, then the minimum across corpora          (becomes am.txt)
  * review.csv     candidates with a y/n "stopword" column to edit by hand; ridf/deficit/dispersion
                   columns are diagnostics that show which frequent words are clustered by topic
Writes src/autostopgen/data/am.txt (+ am.meta.json). Review the list before releasing it.
"""
import argparse
import datetime
import json
import pathlib

import autostopgen
from autostopgen import (METRICS_PAPER, StopwordGenerator, consensus_stopwords, export_review,
                         get_preset, iter_lines)


def write_list(path, words):
    pathlib.Path(path).write_text("\n".join(words) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cc100", required=True, help="CC-100 Amharic file (.txt/.xz/.gz)")
    ap.add_argument("--gpac", required=True, help="GPAC file (line based)")
    ap.add_argument("--top", type=int, default=300)
    ap.add_argument("--block-tokens", type=int, default=1000)
    ap.add_argument("--min-count", type=int, default=50)
    ap.add_argument("--min-df", type=int, default=20)
    ap.add_argument("--consensus", choices=["min", "mean", "none"], default="min")
    ap.add_argument("--review-size", type=int, default=600)
    ap.add_argument("--reuse-state", action="store_true", help="load state_*.tsv.gz from --work-dir instead of recounting")
    ap.add_argument("--out-dir", default=str(pathlib.Path(__file__).resolve().parents[1] / "src/autostopgen/data"))
    ap.add_argument("--work-dir", default="build_out")
    a = ap.parse_args()

    work = pathlib.Path(a.work_dir)
    work.mkdir(parents=True, exist_ok=True)
    kw = dict(top_k=a.top, min_count=a.min_count, min_df=a.min_df, metrics=METRICS_PAPER)
    preset = get_preset("am")

    gens = {}
    for name, path in (("cc100", a.cc100), ("gpac", a.gpac)):
        state = work / f"state_{name}.tsv.gz"
        if a.reuse_state:
            g = StopwordGenerator.load_state(state, tokenizer=preset.tokenizer, normalizer=preset.normalizer,
                                             language="am", **kw)
        else:
            g = StopwordGenerator.from_preset("am", **kw)
            g.partial_fit_stream(iter_lines(path), block_tokens=a.block_tokens)
            g.save_state(state)
        print(f"{name}: {g.n_tokens_:,} tokens, {g.n_docs_:,} blocks, {g.vocab_size_:,} types")
        gens[name] = g

    combined = StopwordGenerator.from_preset("am", **kw)
    for g in gens.values():
        combined.merge(g)
    combined_words = combined.stopwords_
    final = (combined_words if a.consensus == "none"
             else consensus_stopwords(list(gens.values()), top_k=a.top, mode=a.consensus))

    write_list(work / "combined.txt", combined_words)
    write_list(work / "consensus.txt", final)
    combined.to_csv(work / "scores_combined.csv")
    n_rows = export_review(combined, work / "review.csv", selected=final, top=a.review_size)

    out = pathlib.Path(a.out_dir)
    (out / "am.txt").write_text(
        f"# Amharic stopwords generated by autostopgen (tf + idf + entropy, consensus={a.consensus})\n"
        + "\n".join(final) + "\n", encoding="utf-8")
    meta = {
        "language": "am", "autostopgen_version": autostopgen.__version__,
        "built": datetime.date.today().isoformat(),
        "corpora": {n: {"file": pathlib.Path(p).name, "tokens": gens[n].n_tokens_, "blocks": gens[n].n_docs_}
                    for n, p in (("cc100", a.cc100), ("gpac", a.gpac))},
        "block_tokens": a.block_tokens, "min_count": a.min_count, "min_df": a.min_df,
        "metrics": list(METRICS_PAPER), "consensus": a.consensus, "top_k": a.top,
        "token_coverage_combined": round(combined.coverage(final), 4),
        "reviewed_by_hand": False,
    }
    (out / "am.meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    k = min(150, len(final))
    fs, cs = set(final[:k]), set(combined_words[:k])
    print(f"\ntop-{k} overlap between combined-corpus list and consensus list: {len(fs & cs)}/{k}")
    print("only in consensus:", " ".join(w for w in final[:k] if w not in cs)[:700])
    print("only in combined: ", " ".join(w for w in combined_words[:k] if w not in fs)[:700])
    print(f"\nwrote {out / 'am.txt'} ({len(final)} words); work files in {work}/")
    print(f"first 60: {' '.join(final[:60])}")


if __name__ == "__main__":
    main()
